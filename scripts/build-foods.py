def parse_value(v):
    """成分表の値を数にする。Tr・(Tr)・(0) は 0、- は None（未測定）、(12.3) は 12.3（推定値）"""
    if v is None:
        return None
    s = str(v).strip()
    if s in ("", "-", "*"):
        return None
    s = s.strip("()")
    if s in ("Tr", "0"):
        return 0.0
    try:
        return float(s)
    except ValueError:
        return None


